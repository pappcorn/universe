// The pure half of the connector: which strings count as a video, how caption
// XML becomes text, and which caption track a request gets. No network.

import assert from 'node:assert/strict';
import { describe, it } from 'node:test';

import {
  decodeEntities,
  formatClock,
  parseTimedText,
  parseVideoId,
  pickTrack,
  renderPlain,
  renderTimestamped,
  type CaptionTrack,
} from '../src/parse';

const ID = 'abcDEF12_-x';

describe('parseVideoId', () => {
  const accepted = [
    ID,
    `  ${ID}  `,
    `https://www.youtube.com/watch?v=${ID}`,
    `https://youtube.com/watch?v=${ID}&t=42s&list=PL123`,
    `www.youtube.com/watch?v=${ID}`,
    `youtube.com/watch?feature=share&v=${ID}`,
    `https://m.youtube.com/watch?v=${ID}`,
    `https://music.youtube.com/watch?v=${ID}`,
    `https://youtu.be/${ID}`,
    `https://youtu.be/${ID}?si=Share-Tracking_1`,
    `youtu.be/${ID}`,
    `https://www.youtube.com/shorts/${ID}`,
    `https://youtube.com/shorts/${ID}?feature=share`,
    `https://www.youtube.com/embed/${ID}`,
    `https://www.youtube-nocookie.com/embed/${ID}?rel=0`,
    `https://www.youtube.com/live/${ID}`,
    `https://www.youtube.com/v/${ID}`,
    `HTTPS://WWW.YOUTUBE.COM/watch?v=${ID}`,
  ];
  for (const input of accepted) {
    it(`accepts ${input.trim()}`, () => assert.equal(parseVideoId(input), ID));
  }

  const rejected = [
    '',
    'hello',
    'abc',
    `${ID}x`,
    'https://www.youtube.com/@somechannel',
    'https://www.youtube.com/playlist?list=PL123',
    'https://www.youtube.com/watch?v=short',
    `https://example.com/watch?v=${ID}`,
    `https://notyoutube.com/shorts/${ID}`,
    'javascript:alert(1)',
  ];
  for (const input of rejected) {
    it(`rejects ${JSON.stringify(input)} with a readable message`, () =>
      assert.throws(
        () => parseVideoId(input),
        /doesn't look like a link to a YouTube video/,
      ));
  }
});

describe('parseTimedText', () => {
  it('reads the classic format and double-decodes entities', () => {
    const xml =
      '<?xml version="1.0" encoding="utf-8" ?><transcript>' +
      '<text start="1.36" dur="1.68">[Music]</text>' +
      '<text start="18.64" dur="3.24">We&amp;#39;re no strangers &amp;amp; friends</text>' +
      '<text start="22" dur="1">   </text>' +
      '<text start="23.5" dur="2">línea\ncon   espacios</text>' +
      '</transcript>';
    assert.deepEqual(parseTimedText(xml), [
      { start: 1.36, duration: 1.68, text: '[Music]' },
      { start: 18.64, duration: 3.24, text: "We're no strangers & friends" },
      { start: 23.5, duration: 2, text: 'línea con espacios' },
    ]);
  });

  it('strips styling tags, raw or encoded, but keeps a literal "<"', () => {
    const xml =
      '<transcript><text start="0" dur="1">&lt;font color=&quot;#E5E5E5&quot;&gt;hola&lt;/font&gt; a &amp;lt; b</text></transcript>';
    assert.equal(parseTimedText(xml)[0].text, 'hola a < b');
  });

  it('keeps angle brackets people actually said', () => {
    const xml =
      '<transcript>' +
      '<text start="0" dur="1">Vec&amp;lt;String&amp;gt; and x &amp;lt; 5 and y &amp;gt; 3</text>' +
      '</transcript>';
    assert.equal(
      parseTimedText(xml)[0].text,
      'Vec<String> and x < 5 and y > 3',
    );
    const srv3 =
      '<timedtext><body><p t="0" d="1"><s>x &lt; 5 and y &gt; 3</s></p></body></timedtext>';
    assert.equal(parseTimedText(srv3)[0].text, 'x < 5 and y > 3');
  });

  it('cannot assemble a tag by removing one', () => {
    const xml =
      '<transcript><text start="0" dur="1">&lt;scr&lt;b&gt;ipt&gt;x</text></transcript>';
    assert.doesNotMatch(parseTimedText(xml)[0].text, /<script/i);
  });

  it('reads the srv3 format in milliseconds', () => {
    const xml =
      '<timedtext format="3"><body><p t="1200" d="3400"><s>hello</s><s t="500"> world</s></p>' +
      '<p t="5000" d="10"></p></body></timedtext>';
    assert.deepEqual(parseTimedText(xml), [
      { start: 1.2, duration: 3.4, text: 'hello world' },
    ]);
  });

  it('returns nothing for an empty file', () => {
    assert.deepEqual(parseTimedText(''), []);
  });
});

describe('decodeEntities', () => {
  it('handles numeric, hex and named entities, and leaves unknown ones', () => {
    assert.equal(
      decodeEntities('&#233;&#x00F1;&quot;&apos;&bogus;'),
      'éñ"\'&bogus;',
    );
  });
});

const t = (languageCode: string, autoGenerated = false): CaptionTrack => ({
  languageCode,
  autoGenerated,
  name: `${languageCode}${autoGenerated ? ' (auto-generated)' : ''}`,
  baseUrl: `https://www.youtube.com/api/timedtext?lang=${languageCode}${autoGenerated ? '&kind=asr' : ''}`,
});

describe('pickTrack', () => {
  it('prefers an exact uploaded match', () => {
    const tracks = [t('es', true), t('en'), t('es')];
    assert.deepEqual(pickTrack(tracks, 'es'), { track: tracks[2] });
  });

  it('matches regional variants both ways', () => {
    assert.equal(
      pickTrack([t('en'), t('es-419')], 'es').track.languageCode,
      'es-419',
    );
    assert.equal(
      pickTrack([t('en'), t('es')], 'es-MX').track.languageCode,
      'es',
    );
    assert.equal(pickTrack([t('pt-BR')], 'PT-br').track.languageCode, 'pt-BR');
  });

  it('falls back to the spoken language and reports what was asked', () => {
    const r = pickTrack([t('en'), t('es'), t('es', true)], 'de');
    assert.equal(r.track.languageCode, 'es');
    assert.equal(r.track.autoGenerated, false);
    assert.equal(r.fallbackFrom, 'de');
  });

  it('without a wanted language, uses the language that is spoken', () => {
    // A Spanish talk whose channel also uploaded English subtitles, listed first.
    const r = pickTrack(
      [t('en'), t('pt-BR'), t('es'), t('es', true)],
      undefined,
      0,
    );
    assert.equal(r.track.languageCode, 'es');
    assert.equal(r.track.autoGenerated, false);
    assert.equal(r.fallbackFrom, undefined);
  });

  it('uses the auto-generated track when it is the only one in that language', () => {
    assert.deepEqual(pickTrack([t('fr', true)]).track, t('fr', true));
  });

  it("without auto-captions, follows YouTube's default, then the first", () => {
    assert.equal(
      pickTrack([t('en'), t('de')], undefined, 1).track.languageCode,
      'de',
    );
    assert.equal(
      pickTrack([t('en'), t('de')], undefined, 9).track.languageCode,
      'en',
    );
  });
});

describe('rendering', () => {
  it('formats clocks', () => {
    assert.equal(formatClock(0), '0:00');
    assert.equal(formatClock(65.9), '1:05');
    assert.equal(formatClock(3723), '1:02:03');
  });

  it('breaks paragraphs at pauses and after about a minute', () => {
    const segs = [
      { start: 0, duration: 2, text: 'one' },
      { start: 2, duration: 2, text: 'two' },
      { start: 10, duration: 2, text: 'after a pause' },
      ...Array.from({ length: 40 }, (_, i) => ({
        start: 12 + i * 2,
        duration: 2,
        text: `w${i}`,
      })),
    ];
    const paragraphs = renderPlain(segs).split('\n\n');
    assert.equal(paragraphs[0], 'one two');
    assert.ok(paragraphs[1].startsWith('after a pause w0'));
    assert.equal(paragraphs.length, 3);
  });

  it('prefixes every line with its start time', () => {
    assert.equal(
      renderTimestamped([
        { start: 5, duration: 1, text: 'a' },
        { start: 3605, duration: 1, text: 'b' },
      ]),
      '[0:05] a\n[1:00:05] b',
    );
  });
});
