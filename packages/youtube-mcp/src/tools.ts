// MCP tool registration. Tools are thin wrappers over core.ts: validate input,
// call core, format a readable result.
//
// Transport-agnostic: nothing here reads process.env or knows whether it is
// serving stdio. server.ts is what transports share.
//
// THE SURFACE IS SMALL ON PURPOSE. Two tools, both read-only: they read public
// captions and change nothing anywhere, so neither needs a confirmation step.

import { z } from 'zod';
import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';

import { getTranscript, getVideo, type Transcript } from './core';
import { formatClock, renderPlain, renderTimestamped } from './parse';

type TextResult = {
  content: Array<{ type: 'text'; text: string }>;
  isError?: boolean;
};

function ok(text: string): TextResult {
  return { content: [{ type: 'text', text }] };
}

function fail(err: unknown): TextResult {
  const msg = err instanceof Error ? err.message : String(err);
  return { content: [{ type: 'text', text: `ERROR: ${msg}` }], isError: true };
}

/**
 * Each part is sized to stay under the 25k-token default limit Claude Code
 * puts on one tool result, with room for the header. Characters per token vary
 * a lot by script: about 4 for English or Spanish, close to 1 for Chinese,
 * Japanese or Korean. So the budget is in estimated tokens, and the character
 * cap only bounds the Latin-script case (80,000 characters, about an hour and
 * a half of speech).
 */
export const DEFAULT_MAX_CHARS = 80_000;
export const PART_TOKEN_BUDGET = 18_000;

/** Conservative token estimate: CJK and other wide scripts count 1 per char. */
export function tokenCost(ch: string): number {
  const c = ch.codePointAt(0) ?? 0;
  return c >= 0x2e80 ? 1 : c >= 0x0370 ? 0.5 : 0.3;
}

/** How many characters from `offset` fit the token budget, capped at `max`. */
export function charsWithinBudget(
  text: string,
  offset: number,
  max: number,
  budget = PART_TOKEN_BUDGET,
): number {
  let cost = 0;
  let i = offset;
  const end = Math.min(text.length, offset + max);
  while (i < end) {
    cost += tokenCost(text[i]);
    if (cost > budget) break;
    i++;
  }
  return i - offset;
}

const READ_ONLY = {
  readOnlyHint: true,
  destructiveHint: false,
  idempotentHint: true,
  openWorldHint: true,
} as const;

const videoParam = z
  .string()
  .min(1)
  .describe(
    'The YouTube video: a link as pasted (youtube.com/watch?v=…, youtu.be/…, ' +
      'youtube.com/shorts/…, /embed/…, /live/…) or the bare 11-character video id.',
  );

function header(t: Transcript): string[] {
  const v = t.video;
  const lang = t.track.autoGenerated
    ? `${t.track.name} [${t.track.languageCode}]`
    : `${t.track.name} [${t.track.languageCode}], uploaded captions`;
  return [
    `title:     ${v.title}`,
    `channel:   ${v.channel}`,
    `duration:  ${v.durationSeconds ? formatClock(v.durationSeconds) : '(unknown)'}`,
    `url:       ${v.url}`,
    `language:  ${lang}`,
    ...(t.fallbackFrom
      ? [
          `note:      no captions in "${t.fallbackFrom}"; used ${t.track.languageCode} instead. ` +
            `Available: ${[...new Set(v.tracks.map((x) => x.languageCode))].join(', ')}.`,
        ]
      : []),
    ...(t.track.autoGenerated
      ? [
          'note:      these captions were auto-generated by YouTube and can mishear names, ' +
            'terms and figures; treat their spelling with care.',
        ]
      : []),
  ];
}

/**
 * Cut at the best boundary at or before `max` characters: a paragraph break,
 * else a line break (keeps each "[mm:ss]" line whole), else a space; the first
 * of those found in the second half of the window wins. `next` skips the
 * separator, so the following part never starts with whitespace.
 */
export function cutAt(
  text: string,
  offset: number,
  max: number,
): { part: string; next?: number } {
  const rest = text.slice(offset);
  if (rest.length <= max) return { part: rest };
  const window = rest.slice(0, max);
  for (const sep of ['\n\n', '\n', ' ']) {
    const at = window.lastIndexOf(sep);
    if (at > max / 2) {
      return {
        part: rest.slice(0, at).trimEnd(),
        next: offset + at + sep.length,
      };
    }
  }
  return { part: window, next: offset + max };
}

export function registerTools(server: McpServer): void {
  // ── get transcript ───────────────────────────────────────────────────────
  server.registerTool(
    'youtube_get_transcript',
    {
      title: 'Get YouTube transcript',
      description:
        "Read the transcript of a YouTube video from its captions (the channel's own, or " +
        "YouTube's auto-generated ones). Returns the title, channel, duration and the caption " +
        'language actually used, then the text. Use it whenever someone shares a YouTube link ' +
        'and wants it transcribed, summarized, quoted or asked about. Read-only: no account, no ' +
        'API key. If the video has no captions it says so; it never downloads audio. Long ' +
        'videos come in parts: when the result ends with a "continue with offset=N" line, call ' +
        'again with that offset to get the rest.',
      inputSchema: {
        video: videoParam,
        language: z
          .string()
          .optional()
          .describe(
            'Preferred caption language code, e.g. "es", "en", "pt-BR". Matches regional ' +
              'variants ("es" finds "es-419"). If missing, the original spoken language is used ' +
              'and the result notes the substitution. Omit to get the original language.',
          ),
        timestamps: z
          .boolean()
          .optional()
          .describe(
            'true: one caption line per row with its start time, "[12:34] …", for quoting or ' +
              'jumping to a moment. false (default): plain paragraphs.',
          ),
        offset: z
          .number()
          .int()
          .min(0)
          .optional()
          .describe(
            'Character offset to continue a long transcript from. Use the value the previous ' +
              'part gave; omit for the beginning.',
          ),
        max_chars: z
          .number()
          .int()
          .min(2_000)
          .max(400_000)
          .optional()
          .describe(
            `Largest part to return, in characters. Default ${DEFAULT_MAX_CHARS}; parts in ` +
              'scripts that use more tokens per character (Chinese, Japanese, Korean) come smaller.',
          ),
      },
      annotations: { title: 'Get YouTube transcript', ...READ_ONLY },
    },
    async ({ video, language, timestamps, offset, max_chars }) => {
      try {
        const t = await getTranscript(video, language);
        const body = timestamps
          ? renderTimestamped(t.segments)
          : renderPlain(t.segments);
        const start = Math.min(offset ?? 0, body.length);
        const size = charsWithinBudget(
          body,
          start,
          max_chars ?? DEFAULT_MAX_CHARS,
        );
        const { part, next } = cutAt(body, start, Math.max(size, 1));
        const lines = [...header(t)];
        if (start > 0 || next !== undefined) {
          lines.push(
            `part:      characters ${start}–${next ?? body.length} of ${body.length}` +
              (next !== undefined
                ? `; the rest starts at offset=${next}`
                : '; this is the last part'),
          );
        }
        lines.push('', part);
        if (next !== undefined) {
          lines.push(
            '',
            `[transcript continues — call youtube_get_transcript again with the same video and offset=${next}]`,
          );
        }
        return ok(lines.join('\n'));
      } catch (err) {
        return fail(err);
      }
    },
  );

  // ── list languages ───────────────────────────────────────────────────────
  server.registerTool(
    'youtube_list_transcript_languages',
    {
      title: 'List YouTube caption languages',
      description:
        'List the caption languages a YouTube video has, marking which were uploaded by the ' +
        'channel and which YouTube auto-generated, plus the title, channel and duration. ' +
        'Read-only. Use it to pick a language before youtube_get_transcript, or to check ' +
        'whether a video has captions at all.',
      inputSchema: { video: videoParam },
      annotations: { title: 'List YouTube caption languages', ...READ_ONLY },
    },
    async ({ video }) => {
      try {
        const v = await getVideo(video);
        const lines = [
          `title:     ${v.title}`,
          `channel:   ${v.channel}`,
          `duration:  ${v.durationSeconds ? formatClock(v.durationSeconds) : '(unknown)'}`,
          `url:       ${v.url}`,
          '',
        ];
        if (!v.tracks.length) {
          lines.push(
            'No captions: neither uploaded nor auto-generated. There is no transcript to read.',
          );
        } else {
          lines.push('Caption languages:');
          for (const t of v.tracks) {
            lines.push(
              `  ${t.languageCode.padEnd(8)} ${t.name}${t.autoGenerated ? '' : ' (uploaded)'}`,
            );
          }
        }
        return ok(lines.join('\n'));
      } catch (err) {
        return fail(err);
      }
    },
  );
}
