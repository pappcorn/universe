#!/usr/bin/env node
// YouTube CLI: the shell frontend over the shared core. Every command is a thin
// wrapper: parse flags, call the same core functions the MCP tools use, print.
// It is the quickest way to check the connector works from this network before
// an MCP client is in the loop.
//
// Run via: npm run youtube -- <cmd> …
// Exit codes: 0 ok | 2 bad args | 3 YouTube refused or has no captions.

import { getTranscript, getVideo, TranscriptError } from './core';
import {
  InvalidVideoError,
  formatClock,
  renderPlain,
  renderTimestamped,
} from './parse';

const USAGE = `Usage:
  pappcorn-youtube transcript <url-or-id> [--lang <code>] [--timestamps]
  pappcorn-youtube languages  <url-or-id>

Examples:
  pappcorn-youtube transcript https://youtu.be/<id> --lang es
  pappcorn-youtube languages  https://www.youtube.com/shorts/<id>`;

function parseArgs(argv: string[]): {
  positional: string[];
  flags: Record<string, string | boolean>;
} {
  const positional: string[] = [];
  const flags: Record<string, string | boolean> = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) {
      positional.push(a);
    } else if (a.includes('=')) {
      flags[a.slice(2, a.indexOf('='))] = a.slice(a.indexOf('=') + 1);
    } else if (
      argv[i + 1] !== undefined &&
      !argv[i + 1].startsWith('--') &&
      a !== '--timestamps'
    ) {
      flags[a.slice(2)] = argv[++i];
    } else {
      flags[a.slice(2)] = true;
    }
  }
  return { positional, flags };
}

async function main(): Promise<number> {
  const { positional, flags } = parseArgs(process.argv.slice(2));
  const [cmd, video] = positional;
  if (!cmd || flags.help || !video) {
    process.stdout.write(`${USAGE}\n`);
    return cmd && !flags.help ? 2 : 0;
  }

  if (cmd === 'languages') {
    const v = await getVideo(video);
    process.stdout.write(
      `${v.title}\n${v.channel} · ${formatClock(v.durationSeconds)}\n\n` +
        (v.tracks.length
          ? v.tracks
              .map(
                (t) =>
                  `${t.languageCode.padEnd(8)} ${t.name}${t.autoGenerated ? '' : ' (uploaded)'}`,
              )
              .join('\n')
          : 'No captions.') +
        '\n',
    );
    return 0;
  }

  if (cmd === 'transcript') {
    const lang = typeof flags.lang === 'string' ? flags.lang : undefined;
    const t = await getTranscript(video, lang);
    const body = flags.timestamps
      ? renderTimestamped(t.segments)
      : renderPlain(t.segments);
    process.stderr.write(
      `${t.video.title} · ${t.video.channel} · ${formatClock(t.video.durationSeconds)} · ` +
        `${t.track.languageCode}${t.track.autoGenerated ? ' (auto)' : ''}` +
        `${t.fallbackFrom ? ` · no "${t.fallbackFrom}" captions` : ''}\n\n`,
    );
    process.stdout.write(`${body}\n`);
    return 0;
  }

  process.stderr.write(`Unknown command "${cmd}".\n\n${USAGE}\n`);
  return 2;
}

// Set the exit code and let Node exit on its own: process.exit() would drop
// whatever is still buffered when stdout is a pipe (async on macOS).
main().then(
  (code) => {
    process.exitCode = code;
  },
  (err: unknown) => {
    const msg = err instanceof Error ? err.message : String(err);
    process.stderr.write(`${msg}\n`);
    process.exitCode =
      err instanceof InvalidVideoError
        ? 2
        : err instanceof TranscriptError
          ? 3
          : 1;
  },
);
